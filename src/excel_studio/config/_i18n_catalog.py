TRANSLATIONS: dict[str, dict[str, str]] = {"zh_CN": ZH_CN, "en_US": EN_US}


class TranslationManager(QObject):
    language_changed = Signal(str)

    def __init__(self, language: str = "zh_CN") -> None:
        super().__init__()
        self._language = language if language in TRANSLATIONS else "zh_CN"

    @property
    def language(self) -> str:
        return self._language

    def set_language(self, language: str) -> None:
        if language not in TRANSLATIONS or language == self._language:
            return
        self._language = language
        self.language_changed.emit(language)

    def text(self, key: str, **values: object) -> str:
        fallback = TRANSLATIONS["zh_CN"].get(key, key)
        value = TRANSLATIONS[self._language].get(key, fallback)
        return value.format(**values) if values else value

    def translator(self) -> Callable[[str], str]:
        return self.text
